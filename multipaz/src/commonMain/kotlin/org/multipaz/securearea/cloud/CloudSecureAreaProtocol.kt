package org.multipaz.securearea.cloud

import kotlin.time.Duration
import kotlin.time.Instant
import kotlinx.io.bytestring.ByteString
import org.multipaz.cbor.annotation.CborSerializable
import org.multipaz.crypto.Algorithm
import org.multipaz.crypto.EcPublicKey
import org.multipaz.crypto.EcSignature
import org.multipaz.crypto.Signature
import org.multipaz.crypto.X509Cert
import org.multipaz.crypto.X509CertChain
import org.multipaz.rpc.annotation.RpcException
import org.multipaz.rpc.annotation.RpcInterface
import org.multipaz.rpc.annotation.RpcMethod
import org.multipaz.securearea.KeyAttestation

/**
 * Configuration for creating one or more keys in a [CloudSecureArea].
 *
 * @property algorithm the [Algorithm] for the key(s) to be created.
 * @property validFrom timestamp when the key(s) become valid.
 * @property validUntil timestamp when the key(s) expire.
 * @property passphraseRequired whether a passphrase is required to use the key(s).
 * @property userAuthenticationRequired whether user authentication is required to use the key(s).
 * @property userAuthenticationTypes the allowed [CloudUserAuthType]s when user authentication is required.
 * @property challenge the attestation challenge to include in the key attestation.
 */
@CborSerializable
data class CloudKeyConfiguration(
    val algorithm: Algorithm,
    val validFrom: Instant,
    val validUntil: Instant,
    val passphraseRequired: Boolean,
    val userAuthenticationRequired: Boolean,
    val userAuthenticationTypes: Set<CloudUserAuthType>,
    val challenge: ByteString,
) {
    companion object
}

/**
 * Result of creating a single key in a [CloudSecureArea].
 *
 * @property remoteKeyAttestation the attestation certificate chain for the created cloud key.
 * @property serverState opaque encrypted server state representing the created key handle.
 */
@CborSerializable
data class CloudCreatedKey(
    val remoteKeyAttestation: X509CertChain,
    val serverState: ByteString,
) {
    companion object
}

/**
 * Result of batch-creating keys in a [CloudSecureArea].
 *
 * @property commonCertChain the intermediate and root X.509 certificates shared by all created keys.
 * @property remoteKeyAttestationLeafs the leaf X.509 attestation certificate for each created cloud key.
 * @property serverStates opaque encrypted server state for each created cloud key.
 * @property openid4vciKeyAttestationCompactSerialization OpenID4VCI key attestation JWT over all created keys,
 *   or `null` if not provided.
 */
@CborSerializable
data class CloudBatchCreatedKeys(
    val commonCertChain: X509CertChain,
    val remoteKeyAttestationLeafs: List<X509Cert>,
    val serverStates: List<ByteString>,
    val openid4vciKeyAttestationCompactSerialization: String?,
) {
    companion object
}

/**
 * Thrown when the passphrase provided to unlock a cloud key or check the passphrase is incorrect.
 *
 * @property message error description.
 */
@RpcException
@CborSerializable
class CloudWrongPassphraseException(
    override val message: String? = "Wrong passphrase supplied"
) : Exception(message) {
    companion object
}

/**
 * Thrown when too many failed passphrase attempts have occurred and the client is temporarily locked out.
 *
 * @property waitDuration the duration the client must wait before retrying.
 * @property message error description.
 */
@RpcException
@CborSerializable
class CloudTooManyPassphraseAttemptsException(
    val waitDuration: Duration,
    override val message: String? = "Too many passphrase attempts"
) : Exception(message) {
    companion object
}

/**
 * Multipaz CBOR-RPC protocol interface between a [CloudSecureArea] client and server.
 *
 * All methods on this interface are authenticated using [org.multipaz.device.DeviceAssertion] via
 * [org.multipaz.rpc.handler.RpcDispatcherAuth] and [org.multipaz.rpc.handler.RpcAuthIssuerAssertion]
 * after client registration via [org.multipaz.rpc.auth.ClientRegistration].
 */
@RpcInterface
interface CloudSecureAreaProtocol {

    /**
     * Completes registration with the Cloud Secure Area server and sets the user's passphrase.
     *
     * @param passphrase the passphrase to use for passphrase-protected keys.
     * @return the server's key attestation certificate chain so the client can verify its root of trust.
     */
    @RpcMethod
    suspend fun register(
        passphrase: String
    ): X509CertChain

    /**
     * Initiates creation of a single key on the Cloud Secure Area server.
     *
     * @param keyConfiguration configuration for the key to create.
     * @return the challenge generated by the server to be used when creating the companion local key.
     */
    @RpcMethod
    suspend fun createKey0(
        keyConfiguration: CloudKeyConfiguration
    ): ByteString

    /**
     * Completes creation of a single key on the Cloud Secure Area server.
     *
     * @param localKeyAttestation the public key and optional attestation chain of the companion local key.
     * @return the created key's attestation chain and encrypted server state.
     */
    @RpcMethod
    suspend fun createKey1(
        localKeyAttestation: KeyAttestation
    ): CloudCreatedKey

    /**
     * Initiates batch creation of keys on the Cloud Secure Area server.
     *
     * @param keyConfiguration configuration for the batch of keys to create.
     * @return the challenge generated by the server to be used when creating the companion local keys.
     */
    @RpcMethod
    suspend fun batchCreateKey0(
        keyConfiguration: CloudKeyConfiguration
    ): ByteString

    /**
     * Completes batch creation of keys on the Cloud Secure Area server.
     *
     * @param localKeyAttestations the public keys and optional attestation chains of the companion local keys.
     * @return the batch of created keys' attestation certificates, encrypted server states, and optional
     *   OpenID4VCI key attestation JWT.
     */
    @RpcMethod
    suspend fun batchCreateKey1(
        localKeyAttestations: List<KeyAttestation>
    ): CloudBatchCreatedKeys

    /**
     * Initiates signing data with a cloud key.
     *
     * @param dataToSign the data to sign.
     * @param keyContext the encrypted server state for the key.
     * @return the nonce generated by the server to be signed by the companion local key.
     */
    @RpcMethod
    suspend fun sign0(
        dataToSign: ByteString,
        keyContext: ByteString
    ): ByteString

    /**
     * Completes signing data with a cloud key.
     *
     * @param signature the signature over the server nonce made with the companion local key.
     * @param passphrase the passphrase if required for the key, or `null`.
     * @return the resulting signature made with the cloud key.
     * @throws CloudWrongPassphraseException if the passphrase is missing or incorrect.
     * @throws CloudTooManyPassphraseAttemptsException if too many failed passphrase attempts occurred.
     */
    @RpcMethod
    suspend fun sign1(
        signature: EcSignature,
        passphrase: String?
    ): Signature

    /**
     * Initiates key agreement (ECDH) with a cloud key.
     *
     * @param otherPublicKey the other party's public key.
     * @param keyContext the encrypted server state for the key.
     * @return the nonce generated by the server to be signed by the companion local key.
     */
    @RpcMethod
    suspend fun keyAgreement0(
        otherPublicKey: EcPublicKey,
        keyContext: ByteString
    ): ByteString

    /**
     * Completes key agreement (ECDH) with a cloud key.
     *
     * @param signature the signature over the server nonce made with the companion local key.
     * @param passphrase the passphrase if required for the key, or `null`.
     * @return the computed shared secret `Zab`.
     * @throws CloudWrongPassphraseException if the passphrase is missing or incorrect.
     * @throws CloudTooManyPassphraseAttemptsException if too many failed passphrase attempts occurred.
     */
    @RpcMethod
    suspend fun keyAgreement1(
        signature: EcSignature,
        passphrase: String?
    ): ByteString

    /**
     * Initiates decapsulating a shared secret with a KEM cloud key.
     *
     * @param ciphertext the encapsulated ciphertext.
     * @param keyContext the encrypted server state for the key.
     * @return the nonce generated by the server to be signed by the companion local key.
     */
    @RpcMethod
    suspend fun kemDecapsulate0(
        ciphertext: ByteString,
        keyContext: ByteString
    ): ByteString

    /**
     * Completes decapsulating a shared secret with a KEM cloud key.
     *
     * @param signature the signature over the server nonce made with the companion local key.
     * @param passphrase the passphrase if required for the key, or `null`.
     * @return the decapsulated shared secret.
     * @throws CloudWrongPassphraseException if the passphrase is missing or incorrect.
     * @throws CloudTooManyPassphraseAttemptsException if too many failed passphrase attempts occurred.
     */
    @RpcMethod
    suspend fun kemDecapsulate1(
        signature: EcSignature,
        passphrase: String?
    ): ByteString

    /**
     * Checks if the given passphrase matches the registered passphrase.
     *
     * @param passphrase the passphrase to check.
     * @throws CloudWrongPassphraseException if the passphrase is incorrect.
     * @throws CloudTooManyPassphraseAttemptsException if too many failed passphrase attempts occurred.
     */
    @RpcMethod
    suspend fun checkPassphrase(
        passphrase: String
    )
}